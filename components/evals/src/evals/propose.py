import json
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from pydantic import BaseModel, ConfigDict, Field

from router import INTENTS, RoutingConfig, RoutingRule

INTENT_OF_TYPE = {
    "faq": "faq",
    "country_rule": "country_rule",
    "code_switch": "country_rule",
    "claim_status": "claim_status",
}
DEFAULT_GATE = Path(__file__).resolve().parents[2] / "gate.yaml"


class CasePasses(BaseModel):
    model_config = ConfigDict(extra="forbid")

    min_groundedness: float = Field(ge=0, le=1)
    min_relevance: float = Field(ge=0, le=1)
    min_language_fit: float = Field(ge=0, le=1)
    min_polite_form: float = Field(ge=0, le=1)
    require_tool_accuracy: bool
    require_safety: bool


class RoutingBar(BaseModel):
    model_config = ConfigDict(extra="forbid")

    min_cases_per_cell: int = Field(ge=1)
    min_cell_pass_rate: float = Field(gt=0, le=1)


class GateConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    case_passes: CasePasses
    routing: RoutingBar
    gate: dict[str, float]


def load_gate(path: Path | None = None) -> GateConfig:
    return GateConfig.model_validate(yaml.safe_load((path or DEFAULT_GATE).read_text()))


def case_passes(result: dict[str, Any], bar: CasePasses) -> bool:
    scores = result["scores"]

    def at_least(name: str, minimum: float) -> bool:
        value = scores.get(name)
        return value is not None and value >= minimum

    if not at_least("groundedness", bar.min_groundedness):
        return False
    if not at_least("relevance", bar.min_relevance):
        return False
    if not at_least("language_fit", bar.min_language_fit):
        return False
    if scores.get("polite_form") is not None and scores["polite_form"] < bar.min_polite_form:
        return False
    if bar.require_tool_accuracy and scores.get("tool_accuracy") != 1.0:
        return False
    return not (bar.require_safety and scores.get("safety_pass") != 1.0)


@dataclass(frozen=True)
class Cell:
    language: str
    intent: str
    cases: int
    passed: int

    @property
    def rate(self) -> float:
        return self.passed / self.cases if self.cases else 0.0


def load_results(path: Path) -> list[dict[str, Any]]:
    return [
        json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()
    ]


def cells(results: list[dict[str, Any]], bar: CasePasses) -> list[Cell]:
    counts: dict[tuple[str, str], list[int]] = defaultdict(lambda: [0, 0])
    for result in results:
        intent = INTENT_OF_TYPE.get(result["case_type"])
        if intent is None or result.get("error"):
            continue
        entry = counts[(result["language"], intent)]
        entry[0] += 1
        entry[1] += case_passes(result, bar)
    return [Cell(lang, intent, n, ok) for (lang, intent), (n, ok) in sorted(counts.items())]


def propose(
    current: RoutingConfig, small_results: list[dict[str, Any]], gate: GateConfig
) -> tuple[RoutingConfig, list[str]]:
    measured = {(c.language, c.intent): c for c in cells(small_results, gate.case_passes)}
    languages = sorted({r["language"] for r in small_results})
    rules: list[RoutingRule] = []
    notes: list[str] = []
    for language in languages:
        for intent in INTENTS:
            if intent not in INTENT_OF_TYPE.values():
                continue
            cell = measured.get((language, intent))
            if cell is None or cell.cases < gate.routing.min_cases_per_cell:
                seen = 0 if cell is None else cell.cases
                notes.append(f"{language}/{intent}: {seen} case(s), not enough data, kept on large")
                reason = f"not enough small-tier evidence ({seen} case(s))"
            elif cell.rate < gate.routing.min_cell_pass_rate:
                notes.append(
                    f"{language}/{intent}: small passed {cell.passed}/{cell.cases}, use large"
                )
                reason = f"small passed {cell.passed}/{cell.cases} on the golden set"
            else:
                notes.append(f"{language}/{intent}: small passed {cell.passed}/{cell.cases}")
                continue
            rules.append(
                RoutingRule(
                    language=language,
                    intent=intent,
                    tier="large",
                    reason=reason,
                )
            )
    proposed = current.model_copy(update={"rules": rules, "version": current.version + 1})
    return proposed, notes


def render_yaml(config: RoutingConfig, notes: list[str]) -> str:
    header = [
        "# PROPOSED routing, generated by `propose-routing` from evaluation results.",
        "# A human reviews this and copies it to components/router/routing.yaml.",
        "# Evidence:",
        *[f"#   {line}" for line in notes],
    ]
    body = yaml.safe_dump(
        json.loads(config.model_dump_json(exclude_none=True)), sort_keys=False, allow_unicode=True
    )
    return "\n".join(header) + "\n" + body
